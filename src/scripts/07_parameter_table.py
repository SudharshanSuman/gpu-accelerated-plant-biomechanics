"""Emit the authoritative parameter table, read straight from the code.

Parameter tables in papers drift away from the code they describe, and a
reviewer who spots the gap stops trusting everything else. This generates
`Documentation/PARAMETERS.md` (and a LaTeX version) directly from
`plantsim.config`, so the table cannot disagree with what was actually run.

Re-run it whenever a parameter changes, and paste the LaTeX block into the
paper rather than retyping numbers.
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

import numpy as np

from _bootstrap import ROOT
from plantsim import SimConfig, build_template

# (attribute path, symbol, unit, printed precision, justification)
ROWS = [
    ("gravity", "g", "m/s²", None, "standard gravity"),
    ("stem.length", "L", "m", 2, "row crop at working height"),
    ("stem.n_nodes", "n", "–", 0, "converged at this resolution; see VALIDATION.md"),
    ("stem.radius_base", "r_base", "mm", 1, "calliper-measurable; sets EI at the clamp"),
    ("stem.radius_tip", "r_tip", "mm", 1, "taper gives EI ∝ r⁴ falloff with height"),
    ("stem.youngs_modulus", "E_stem", "GPa", 2,
     "green herbaceous stem, published range ≈0.3–5 GPa; values below ≈0.2 GPa "
     "cannot support the stem's own weight (see material sanity check)"),
    ("stem.density", "ρ_stem", "kg/m³", 0, "fresh tissue, mostly water"),
    ("stem.drag_coefficient", "Cd_stem", "–", 2, "bluff cylinder in cross-flow"),
    ("leaf.youngs_modulus", "E_leaf", "GPa", 2, "lamina ≈10× more compliant than stem"),
    ("leaf.length", "L_leaf", "m", 3, "blade length"),
    ("leaf.width", "w_leaf", "m", 3, "sets drag area"),
    ("leaf.drag_coefficient", "Cd_leaf", "–", 2, "flat plate normal to flow"),
    ("wind.speed", "U", "m/s", 1, "moderate breeze at reference height"),
    ("wind.shear_exponent", "α", "–", 2, "power-law boundary layer over cropland"),
    ("wind.air_density", "ρ_air", "kg/m³", 3, "ISA sea level"),
    ("solver.dt", "Δt", "s", 5, "60 Hz frame"),
    ("solver.substeps", "n_sub", "–", 0, "converged; see convergence study"),
    ("solver.iterations", "n_iter", "–", 0, "converged; see convergence study"),
    ("solver.velocity_damping", "c", "1/s", 2, "ζ≈0.1 at ~1.5 Hz; rate, not per-frame factor"),
]

SCALE = {"mm": 1000.0, "GPa": 1e-9, "MPa": 1e-6}


def resolve(cfg, path):
    value = cfg
    for part in path.split("."):
        value = getattr(value, part)
    return value


def main() -> int:
    cfg = SimConfig()
    tpl = build_template(cfg)

    md = [
        "# Parameters — authoritative table",
        "",
        "**Generated from `src/plantsim/config.py` by "
        "`src/scripts/07_parameter_table.py`. Do not edit by hand.**",
        "",
        "Any parameter value quoted anywhere else — in the paper, in slides, in "
        "`Physics_and_Code_Description.md` — must match this table. If it does "
        "not, this table is right, because it is what the code actually ran.",
        "",
        "| Symbol | Value | Unit | Basis |",
        "|---|---:|---|---|",
    ]
    tex = [
        "% Generated by src/scripts/07_parameter_table.py -- do not edit by hand",
        "\\begin{table}[t]",
        "\\caption{Simulation parameters. Material constants are taken from "
        "published ranges for green herbaceous tissue; geometry describes a "
        "row crop at working height.}",
        "\\label{tab:parameters}",
        "\\centering",
        "\\begin{tabular}{llll}",
        "\\toprule",
        "Symbol & Value & Unit & Basis \\\\",
        "\\midrule",
    ]

    for path, symbol, unit, precision, basis in ROWS:
        raw = resolve(cfg, path)
        if isinstance(raw, tuple):
            shown = ", ".join(f"{v:g}" for v in raw)
        else:
            value = raw * SCALE.get(unit, 1.0)
            shown = f"{value:.{precision}f}" if precision is not None else f"{value:g}"
        md.append(f"| {symbol} | {shown} | {unit} | {basis} |")
        tex_basis = basis.replace("≈", "$\\approx$").replace("×", "$\\times$")
        tex_basis = tex_basis.replace("∝", "$\\propto$").replace("⁴", "$^4$")
        tex_basis = tex_basis.replace("ζ", "$\\zeta$").replace("–", "--")
        tex_symbol = symbol.replace("ρ", "$\\rho$").replace("α", "$\\alpha$")
        tex_symbol = tex_symbol.replace("Δ", "$\\Delta$").replace("_", "\\_")
        tex.append(f"{tex_symbol} & {shown} & {unit.replace('³','$^3$').replace('²','$^2$').replace('–','--')} & {tex_basis} \\\\")

    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    stem_hinges = tpl.bend_compliance[: cfg.stem.n_nodes - 2]
    md += [
        "",
        "## Derived quantities",
        "",
        "These are not inputs — they follow from the table above.",
        "",
        "| Quantity | Value | How |",
        "|---|---:|---|",
        f"| Flexural rigidity at base | {cfg.stem.youngs_modulus * np.pi * cfg.stem.radius_base ** 4 / 4:.4f} N·m² | EI, I = πr⁴/4 |",
        f"| Flexural rigidity at tip | {cfg.stem.youngs_modulus * np.pi * cfg.stem.radius_tip ** 4 / 4:.4f} N·m² | EI, I = πr⁴/4 |",
        f"| Base/tip rigidity ratio | {stem_hinges[-1] / stem_hinges[0]:.0f}× | from the r⁴ taper |",
        f"| Plant mass | {1000 * tpl.mass[:-1].sum():.1f} g | ρ·A·L, lumped at nodes |",
        f"| Particles per plant | {tpl.n_nodes} | stem + leaves + soil anchor |",
        f"| Constraints per plant | {len(tpl.stretch_rest) + len(tpl.bend_rest)} | axial + bending |",
        f"| Solver substep h | {cfg.solver.dt / cfg.solver.substeps * 1000:.3f} ms | Δt / n_sub |",
    ]

    out_md = ROOT / "Documentation" / "PARAMETERS.md"
    out_md.write_text("\n".join(md) + "\n")
    out_tex = ROOT / "paper" / "parameters.tex"
    out_tex.parent.mkdir(exist_ok=True)
    out_tex.write_text("\n".join(tex) + "\n")

    print("\n".join(md))
    print()
    print(f"wrote {out_md}")
    print(f"wrote {out_tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
