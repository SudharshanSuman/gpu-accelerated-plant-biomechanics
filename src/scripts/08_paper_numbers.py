r"""Emit every number the paper quotes as a LaTeX macro, generated from runs.

Retyping results into a manuscript is how a paper ends up claiming a figure
the code never produced. Instead this writes `paper/results_macros.tex` full
of `\newcommand` definitions, and the manuscript references
`\TipDeflection` rather than a literal "0.26 m". Re-run after any change and
the paper updates itself.

Numbers that do not exist yet (GPU timings, field measurements) are emitted as
a loud placeholder rather than a plausible-looking value, so an unfilled slot
is impossible to miss in the compiled PDF.
"""

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

import numpy as np

from _bootstrap import RESULTS, ROOT
from plantsim import SimConfig, build_template
from plantsim.solver import PlantSolver

MISSING = r"\textbf{??}"


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main() -> int:
    cfg = SimConfig()
    tpl = build_template(cfg)
    lines = [
        "% Generated by src/scripts/08_paper_numbers.py -- do not edit by hand.",
        "% Re-run after changing parameters or re-running experiments.",
        "",
    ]

    # ---- plant and solver configuration ----
    stem_hinges = tpl.bend_compliance[: cfg.stem.n_nodes - 2]
    lines += [
        macro("StemLength", f"{cfg.stem.length:.2f}"),
        macro("StemNodes", f"{cfg.stem.n_nodes}"),
        macro("RadiusBase", f"{cfg.stem.radius_base * 1000:.1f}"),
        macro("RadiusTip", f"{cfg.stem.radius_tip * 1000:.1f}"),
        macro("YoungsModulus", f"{cfg.stem.youngs_modulus / 1e9:.1f}"),
        macro("RigidityRatio", f"{stem_hinges[-1] / stem_hinges[0]:.0f}"),
        macro("ParticlesPerPlant", f"{tpl.n_nodes}"),
        macro("ConstraintsPerPlant", f"{len(tpl.stretch_rest) + len(tpl.bend_rest)}"),
        macro("Substeps", f"{cfg.solver.substeps}"),
        macro("Iterations", f"{cfg.solver.iterations}"),
        macro("WindSpeed", f"{cfg.wind.speed:.1f}"),
        "",
    ]

    # ---- wind response ----
    print("simulating wind response...")
    windy = SimConfig()
    windy.scene.height_jitter = 0.0
    solver = PlantSolver(windy)
    deflections = []
    for frame in range(420):
        solver.step()
        if frame >= 60:
            deflections.append(solver.tip_deflection()[0])
    solver.sync()
    deflections = np.array(deflections)
    stem = solver.positions()[solver.scene.plant_slice(0)][tpl.stem_path]
    lines += [
        macro("TipDeflectionMean", f"{deflections.mean():.3f}"),
        macro("TipDeflectionPeak", f"{deflections.max():.3f}"),
        macro("TipDeflectionPercent", f"{100 * deflections.max() / windy.stem.length:.0f}"),
        macro("TipHeight", f"{stem[-1, 1]:.3f}"),
        "",
    ]

    # ---- benchmark ----
    bench_path = RESULTS / "benchmark.json"
    if bench_path.exists():
        rows = json.loads(bench_path.read_text())
        biggest = max(rows, key=lambda r: r["particles"])
        has_cuda = not np.isnan(biggest.get("warp_cuda_ms", float("nan")))
        lines += [
            macro("BenchMaxPlants", f"{biggest['plants']}"),
            macro("BenchMaxParticles", f"{biggest['particles']}"),
            macro("BenchWarpCPU", f"{biggest['warp_cpu_ms']:.1f}"),
            macro("BenchRepeats", f"{biggest.get('repeats', 1)}"),
            macro("BenchWarpCUDA",
                  f"{biggest['warp_cuda_ms']:.2f}" if has_cuda else MISSING),
            macro("Speedup",
                  f"{biggest['speedup_vs_warp_cpu']:.1f}" if has_cuda else MISSING),
            macro("GPUAvailable", "true" if has_cuda else "false"),
            "",
        ]
        if not has_cuda:
            lines.insert(2, "% WARNING: no CUDA timings. \\BenchWarpCUDA and "
                            "\\Speedup are placeholders.")

    # ---- field validation ----
    field_md = RESULTS / "field_validation.md"
    lines.append(macro("FieldValidationDone",
                       "true" if field_md.exists() else "false"))
    if not field_md.exists():
        lines += [
            macro("FieldN", MISSING),
            macro("FieldMAE", MISSING),
            macro("FieldSpecies", MISSING),
            "% WARNING: no field measurements yet. Run 06_field_validation.py.",
        ]

    out = ROOT / "paper" / "results_macros.tex"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")

    missing = [l for l in lines if MISSING in l]
    if missing:
        print(f"\n{len(missing)} macro(s) are UNFILLED placeholders:")
        for m in missing:
            print(f"  {m}")
        print("\nThese render as bold ?? in the PDF. They must be filled before")
        print("submission -- do not substitute estimates.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
